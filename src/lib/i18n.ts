/** Повідомлення про помилку з SQL-функцій ("BID_TOO_LOW:140" → "Ставка замала. Мінімум: 140"). */
export function errorText(d: Dict, message: string | undefined): string {
  const raw = message ?? "";
  const [code, arg] = raw.split(":");
  const known = d.errors[code as keyof Dict["errors"]];
  return known ? known + (arg ?? "") : d.errors.generic + (raw ? ` (${raw})` : "");
}
